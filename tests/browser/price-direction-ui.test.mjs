import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {Journal} from '../../src/journal.mjs';
import {createApp} from '../../src/server.mjs';
import {GuardianService} from '../../src/service.mjs';
import {DedicatedBrowser} from '../../src/browser.mjs';
import {ratioFixture} from '../helpers/ratio-review-fixture.mjs';

for(const width of [960,1440])test('separate increase and reduction workspaces retain whole-product consent '+width,{timeout:60000},async()=>{
 const dir=await mkdtemp(join(tmpdir(),'guardian-direction-ui-')),j=new Journal(':memory:'),now=Date.now();
 const up=ratioFixture(j,{now}),down=ratioFixture(j,{now,mixed:true,productId:'300002'});
 const increase=j.recordRemovalPriceReview(up.plan,up.loss,now),decrease=j.recordRemovalPriceReview(down.plan,down.loss,now);
 const platform={progress:{stage:'test'},probe:async()=>({shopId:up.policy.shopId,name:'调价分区测试店'})};
 const service=new GuardianService({journal:j,platform,policy:up.policy});
 const browser=new DedicatedBrowser(join(dir,'browser'),{test:true,viewport:{width,height:960}});
 const app=await createApp({config:up.policy,runtime:join(dir,'server'),port:0,dependencies:{journal:j,service,platform,browser:{close:async()=>{}}}});
 try{
  const html=await(await fetch(app.url)).text(),token=html.match(/<script nonce="([^"]+)"/)[1];
  await fetch(app.url+'/api/finish-login',{method:'POST',headers:{Origin:app.url,'Content-Type':'application/json','X-Guardian-Token':token},body:'{}'});
  for(let i=0;i<50&&!app.snapshot().connection;i++)await new Promise(r=>setTimeout(r,10));
  await browser.open(up.policy.shopId);const page=await browser.page(),errors=[],posts=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.method()==='POST')posts.push(r.postDataJSON());});
  await page.goto(app.url);await page.locator('[data-view="prices"]').click();
  const upCard=page.locator(`[data-review-id="${increase.id}"]`),downCard=page.locator(`[data-review-id="${decrease.id}"]`);
  await upCard.waitFor();assert.equal(await downCard.count(),0);
  assert.equal(await page.locator('#price-increase-count').innerText(),'1');
  assert.equal(await page.locator('#price-decrease-count').innerText(),'1');
  await upCard.getByRole('checkbox').check();
  await upCard.locator('[data-price-option="raise-low"]').click();
  assert.equal(await upCard.getByRole('checkbox').isChecked(),false,'strategy switching clears consent');
  assert.equal(await upCard.locator('[data-price-option]').count(),4);
  await page.locator('[data-price-direction="decrease"]').click();
  await downCard.waitFor();assert.equal(await upCard.count(),0);
  assert.equal(await downCard.getByRole('checkbox').count(),0,'a reduction is never selected by default');
  assert.equal(await downCard.locator('[data-price-option="raise-low"]').isDisabled(),true);
  assert.match(await downCard.locator('[data-price-option="switch-original"]').innerText(),/尚未通过目标活动/);
  await downCard.locator('[data-price-option="original"]').click();
  assert.equal(await downCard.locator('tbody tr').count(),2);
  assert.match(await downCard.locator('.price-lower-warning').innerText(),/¥95.57/);
  assert.equal(await downCard.getByRole('checkbox').isChecked(),false);
  await page.screenshot({path:join(import.meta.dirname,`../../artifacts/beta22-price-decrease-${width}.png`)});
  await page.locator('[data-price-direction="increase"]').click();await upCard.waitFor();
  assert.equal(await upCard.getByRole('checkbox').isChecked(),false,'tab switching must clear consent');
  await page.screenshot({path:join(import.meta.dirname,`../../artifacts/beta22-price-increase-${width}.png`)});
  assert.equal(posts.length,0);
  await upCard.getByRole('checkbox').check();
  await upCard.getByRole('button',{name:'确认表内价格并继续守护',exact:true}).click();
  await page.getByText('当前没有待确认的提价方案。',{exact:true}).waitFor();
  assert.equal(j.priceTarget(up.policy.shopId,increase.productId)?.id,increase.id);
  assert.equal(j.priceTarget(up.policy.shopId,decrease.productId),null);
  await page.locator('[data-price-direction="decrease"]').click();await downCard.waitFor();
  await downCard.locator('[data-price-option="original"]').click();
  await downCard.getByRole('checkbox').check();
  await downCard.getByRole('button',{name:'确认表内价格并继续守护',exact:true}).click();
  await page.getByText('当前没有待确认的降价方案。',{exact:true}).waitFor();
  assert.equal(j.priceTarget(up.policy.shopId,decrease.productId)?.id,decrease.id);
  assert.equal(posts.length,2);
  assert.deepEqual(posts[1].confirmedSkuIds,decrease.rows.map(r=>r.id));
  await page.locator('[data-price-direction="all"]').click();
  await page.waitForFunction(()=>document.querySelectorAll('.price-review').length===2);
  assert.equal(await page.locator('.price-consent input').count(),0);
  assert.equal(j.list(up.policy.shopId).length,0,'UI confirmation only records exact consent');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await app.close();await rm(dir,{recursive:true,force:true});}
});
